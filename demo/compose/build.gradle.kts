// tur Android demo app — runs the full rut playground on a single `TurView`.
// The playground's rut sources are embedded in `libtur_demo.so`
// (`demo/compose/native` — `include_str!` of `rut/playground/*`), so there is
// no module asset to stage. Build with `./gradlew assembleRelease` (arm64-v8a
// only; the native .so is aarch64-linux-android).

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
}

android {
    namespace = "org.tur.demo"
    compileSdk = 34

    defaultConfig {
        applicationId = "org.tur.demo"
        minSdk = 24
        targetSdk = 34
        versionCode = 1
        versionName = "0.1.0"

        ndk {
            // arm64-v8a only — real Android devices. The x86_64 emulator
            // build was removed; it tripled the APK size for a debug-only
            // smoke-test convenience.
            abiFilters += "arm64-v8a"
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
    }

    composeOptions {
        kotlinCompilerExtensionVersion = "1.5.15"
    }

    sourceSets {
        getByName("main") {
            // jniLibs is the standard AGP location for prebuilt .so files.
            // libtur_demo.so (built by the buildDemoNative task below) lands here.
            jniLibs.srcDirs("src/main/jniLibs")
        }
    }
}

dependencies {
    implementation(project(":tur-compose"))

    implementation("androidx.core:core-ktx:1.13.1")
    implementation("androidx.activity:activity-compose:1.9.3")
    implementation(platform("androidx.compose:compose-bom:2024.10.01"))
    implementation("androidx.compose.ui:ui")
    implementation("androidx.compose.material3:material3")
    implementation("androidx.compose.foundation:foundation")
    implementation("androidx.compose.runtime:runtime")
}

// --- Native build: cargo ndk → jniLibs --------------------------------------
//
// The demo's `libtur_demo.so` is cross-compiled from `demo/compose/native` (a
// cdylib that links `libs/tur-android` as an rlib + the demo plugin set). It
// exports both the demo's `createEngine` JNI fn and the standard engine-op
// fns (`Java_org_tur_TurNative_*`, generated by `tur_android::standard_jni_exports!`).

val workspaceRoot = rootProject.projectDir.parentFile.parentFile // demo/compose → repo root
val demoNativeCrate = File(projectDir, "native")
val jniLibsArm64 = File(projectDir, "src/main/jniLibs/arm64-v8a")

val cargoProfile = project.findProperty("turCargoProfile") as String? ?: "release"
val cargoAbis = listOf("arm64-v8a" to "aarch64")
val cargoArtifacts = cargoAbis.map { (abi, arch) ->
    abi to File(workspaceRoot, "target/$arch-linux-android/${cargoProfile}/libtur_demo.so")
}

val buildDemoNative by tasks.registering(Exec::class) {
    group = "tur"
    description = "Cross-compile libtur_demo.so via cargo-ndk."
    inputs.dir(File(demoNativeCrate, "src"))
    inputs.file(File(demoNativeCrate, "Cargo.toml"))
    inputs.file(File(workspaceRoot, "Cargo.toml"))
    cargoArtifacts.forEach { (_, file) -> outputs.file(file) }

    val profileArgs = if (cargoProfile == "release") listOf("--release") else emptyList()
    val targetArgs = cargoAbis.flatMap { (_, arch) -> listOf("-t", "$arch-linux-android") }
    commandLine(
        "cargo", "ndk",
        *targetArgs.toTypedArray(),
        "build",
        "--manifest-path", File(demoNativeCrate, "Cargo.toml").absolutePath,
        *profileArgs.toTypedArray(),
    )
    environment("ANDROID_NDK_HOME", System.getenv("ANDROID_NDK_HOME")
        ?: File(System.getenv("ANDROID_HOME") ?: "", "ndk/27.0.12077973").absolutePath)
}

val copyDemoNative by tasks.registering(DefaultTask::class) {
    group = "tur"
    description = "Copy the built libtur_demo.so into jniLibs/."
    dependsOn(buildDemoNative)
    cargoArtifacts.forEach { (_, artifact) -> inputs.file(artifact) }
    doLast {
        cargoArtifacts.forEach { (abi, artifact) ->
            val dir = File(jniLibsArm64.parentFile, abi)
            dir.mkdirs()
            artifact.copyTo(File(dir, "libtur_demo.so"), overwrite = true)
        }
    }
}

// Make sure the .so is present before the APK packages jniLibs. AGP 8.x names
// the jniLibs merge task `merge<Variant>JniLibFolders`.
android.applicationVariants.all {
    val variantCapitalized = name.replaceFirstChar { it.uppercase() }
    tasks.matching { it.name == "merge${variantCapitalized}JniLibFolders" }
        .configureEach { dependsOn(copyDemoNative) }
}

// (The playground ships as rut sources embedded in the demo's cdylib — there
// is no module-asset pipeline to stage. See demo/compose/native/src/lib.rs.)

// --- Keep `.symtab` in the packaged native lib --------------------------------
//
// AGP's `stripReleaseDebugSymbols` strips the ELF symbol table (`.symtab`) from
// prebuilt jniLibs in release builds. `debugSymbolLevel = "symbol_table"` only
// affects native code AGP builds itself (cmake/ndk-build) — for prebuilt `.so`
// files like ours (built by `cargo ndk`), the strip always removes `.symtab`,
// leaving on-device `std::backtrace::Backtrace` captures (the panic hook in
// `tur-android/src/lib.rs`) unable to resolve function names.
//
// Append a `doLast` that overwrites the stripped output with the unstripped
// merged `.so`, so the APK ships with the symbol table intact and panic
// backtraces in logcat are symbolicated. The cargo release build has no DWARF
// sections, so the only cost is the `.symtab`/`.strtab` size (~14 MB).
tasks.matching { it.name == "stripReleaseDebugSymbols" }.configureEach {
    val merged = layout.buildDirectory.file(
        "intermediates/merged_native_libs/release/mergeReleaseNativeLibs/out/lib/arm64-v8a/libtur_demo.so"
    )
    val strippedOut = layout.buildDirectory.file(
        "intermediates/stripped_native_libs/release/stripReleaseDebugSymbols/out/lib/arm64-v8a/libtur_demo.so"
    )
    doLast {
        val src = merged.get().asFile
        val dst = strippedOut.get().asFile
        if (src.exists() && dst.parentFile.exists()) {
            src.copyTo(dst, overwrite = true)
            logger.lifecycle("strip: restored unstripped libtur_demo.so (kept .symtab for panic backtraces): ${dst.length()} bytes")
        }
    }
}
