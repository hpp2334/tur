// Generates `cases_gen.rut` — the playground's case registry as a rut
// module fragment: `pg_case_count()`, `pg_case_name(i)`, and
// `pg_case_source(name)` over the embedded sources. Concatenated after
// `playground.rut` by the website's `playgroundSource()` (the two halves
// compile as ONE module), so the playground sidebar lists every case
// without any fetch/host I/O.
//
// Sources cases from ONE directory: the shared engine test corpus
// (`js/packages/tur-test-cases/cases`, `index.rut` each).
const fs = require("node:fs");
const path = require("node:path");

const workspaceRoot = path.resolve(__dirname, "..", "..", "..");
const engineCasesDir = path.join(workspaceRoot, "js", "packages", "tur-test-cases", "cases");
const outFile = path.resolve(__dirname, "..", "cases_gen.rut");

const cases = [];
if (fs.existsSync(engineCasesDir)) {
    for (const name of fs.readdirSync(engineCasesDir).sort()) {
        const caseDir = path.join(engineCasesDir, name);
        if (!fs.statSync(caseDir).isDirectory()) continue;
        const indexFile = path.join(caseDir, "index.rut");
        if (!fs.existsSync(indexFile)) continue;
        cases.push({ name, source: fs.readFileSync(indexFile, "utf8") });
    }
}

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

const nameArms = cases
    .map((c, i) => `    if (i == ${i}) {\n        return "${esc(c.name)}";\n    }`)
    .join("\n");
const sourceArms = cases
    .map((c) => `    if (name == "${esc(c.name)}") {\n        return "${esc(c.source)}";\n    }`)
    .join("\n");

const code = `// AUTO-GENERATED by scripts/gen-cases.cjs — do not edit.
// The playground's case registry: one entry per corpus case
// (js/packages/tur-test-cases/cases/<name>/index.rut).

fn pg_case_count() -> u64 {
    return ${cases.length};
}

fn pg_case_name(i: u64) -> str {
${nameArms}
    return "";
}

fn pg_case_source(name: str) -> str {
${sourceArms}
    return "";
}
`;

fs.writeFileSync(outFile, code);
console.log(`generated cases_gen.rut with ${cases.length} cases`);
