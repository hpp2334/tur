#[test]
fn core_is_mechanism_only() {
    let core = workspace_root().join("libs/tur-engine/src/core");
    let mut files = Vec::new();
    collect_rs(&core, &mut files);
    assert!(
        files.len() > 50,
        "core source scan found {} files — the walker is broken",
        files.len()
    );

    let mut violations = Vec::new();
    for file in files {
        let Ok(src) = std::fs::read_to_string(&file) else {
            continue;
        };
        for (line_no, line) in src.lines().enumerate() {
            if line.contains("builtin_plugins") {
                violations.push(format!(
                    "{}:{}: core references builtin_plugins: {}",
                    file.display(),
                    line_no + 1,
                    line.trim()
                ));
            }
        }
    }
    assert!(
        violations.is_empty(),
        "the layering law: core must own mechanism, never elements —\n{}",
        violations.join("\n")
    );
}

#[test]
fn no_shared_builder_contract() {
    // The shared builder contract is gone: every element family owns its
    // spec + rows + its own `*_build` terminal. The generic rows and the
    // `RutBuilder`-style trait must never reappear outside the plugins
    // (the kit wraps family rows; core knows nothing of builders).
    let engine = workspace_root().join("libs/tur-engine/src");
    let mut files = Vec::new();
    collect_rs(&engine, &mut files);

    let forbidden = ["el_build(", "el_child(", "el_qkey(", "el_vqkey("];
    let mut violations = Vec::new();
    for file in files {
        let Ok(src) = std::fs::read_to_string(&file) else {
            continue;
        };
        for (line_no, line) in src.lines().enumerate() {
            // `RutBuilder` anywhere is a violation.
            if line.contains("RutBuilder") {
                violations.push(format!(
                    "{}:{}: a shared RutBuilder contract reappeared: {}",
                    file.display(),
                    line_no + 1,
                    line.trim()
                ));
            }
            for row in forbidden {
                if line.contains(row) {
                    violations.push(format!(
                        "{}:{}: the generic `{}` row reappeared: {}",
                        file.display(),
                        line_no + 1,
                        row.trim_end_matches('('),
                        line.trim()
                    ));
                }
            }
        }
    }
    assert!(
        violations.is_empty(),
        "the layering law: every family owns its rows; no shared builder \
         contract may reappear —\n{}",
        violations.join("\n")
    );
}

/// The `tur_host` exposure law: the host pkg is reachable ONLY through the
/// kits (`rut/tur_kit` / `tur_anim_kit` / `tur_net_kit`). Scans every
/// `.rut` source and every `.rs` source (inline snippets included) under
/// `rut/`, `libs/`, and `demo/`; the documented exceptions live in
/// [`TUR_HOST_IMPORT_EXCEPTIONS`].
#[test]
fn tur_host_is_kits_only() {
    let root = workspace_root();
    let mut files = Vec::new();
    for dir in ["rut", "libs", "demo"] {
        collect_rut_sources(&root.join(dir), &mut files);
    }
    assert!(
        files.len() > 300,
        "the surface scan found {} files — the walker is broken",
        files.len()
    );

    let mut violations = Vec::new();
    for file in files {
        let rel = file
            .strip_prefix(&root)
            .unwrap_or(&file)
            .to_string_lossy()
            .to_string();
        if rel.ends_with("tests/layering.rs")
            || TUR_HOST_IMPORT_EXCEPTIONS.iter().any(|(s, _)| rel.contains(s))
        {
            // The law's own source names the spellings it bans.
            continue;
        }
        let Ok(src) = std::fs::read_to_string(&file) else {
            continue;
        };
        for (line_no, line) in src.lines().enumerate() {
            if code_line(line) && line.contains("use tur_host") {
                violations.push(format!(
                    "{}:{}: tur_host is kits-only (see TUR_HOST_IMPORT_EXCEPTIONS): {}",
                    rel,
                    line_no + 1,
                    line.trim()
                ));
            }
        }
    }
    assert!(
        violations.is_empty(),
        "the surface law: `use tur_host` outside the kits —\n{}",
        violations.join("\n")
    );
}

/// The raw-rail law: `rs_derive` / `rs_derive2` / `rs_watch` never appear
/// at CALL sites — the kit's typed surface (`derive<T>` / `watch<T>`) is
/// the authored spelling; the plain-fn wrappers live kit-internally
/// (definitions are skipped). The playground's status label and the perf
/// scene ride the documented upstream accommodations.
#[test]
fn raw_reactive_rail_has_no_call_sites() {
    let root = workspace_root();
    let mut files = Vec::new();
    for dir in ["rut", "libs", "demo"] {
        collect_rut_sources(&root.join(dir), &mut files);
    }

    let mut violations = Vec::new();
    for file in files {
        let rel = file
            .strip_prefix(&root)
            .unwrap_or(&file)
            .to_string_lossy()
            .to_string();
        if rel.ends_with("tests/layering.rs")
            || RAW_RAIL_CALL_EXCEPTIONS.iter().any(|(s, _)| rel.contains(s))
        {
            continue;
        }
        let Ok(src) = std::fs::read_to_string(&file) else {
            continue;
        };
        for (line_no, line) in src.lines().enumerate() {
            if !code_line(line) {
                continue;
            }
            let t = line.trim();
            // A definition line (`pub fn rs_derive(` / `fn rs_watch(`) is
            // the wrapper's home, not a call site.
            if t.contains("fn rs_derive(") || t.contains("fn rs_derive2(") || t.contains("fn rs_watch(")
            {
                continue;
            }
            if t.contains("rs_derive(") || t.contains("rs_derive2(") || t.contains("rs_watch(") {
                violations.push(format!(
                    "{}:{}: the raw reactive rail has no call sites (use the \
                     kit's derive<T>/watch<T>): {}",
                    rel,
                    line_no + 1,
                    t
                ));
            }
        }
    }
    assert!(
        violations.is_empty(),
        "the raw-rail law: rs_derive/rs_derive2/rs_watch at a call site —\n{}",
        violations.join("\n")
    );
}

/// The stash law: `st_put` / `st_take` / `stf_put` / `stf_take` are
/// DELETED rows (phase 5) — zero spellings anywhere, in any `.rut` source
/// or `.rs` inline snippet. The compiler enforces the rows' absence; this
/// scan pins that the spellings never reintroduce (a re-added row would
/// fail here before it gains a user).
#[test]
fn stash_spellings_are_gone() {
    let root = workspace_root();
    let mut files = Vec::new();
    for dir in ["rut", "libs", "demo"] {
        collect_rut_sources(&root.join(dir), &mut files);
    }
    assert!(
        files.len() > 300,
        "the stash scan found {} files — the walker is broken",
        files.len()
    );

    let spellings = ["st_put", "st_take", "stf_put", "stf_take"];
    let mut violations = Vec::new();
    for file in files {
        let rel = file
            .strip_prefix(&root)
            .unwrap_or(&file)
            .to_string_lossy()
            .to_string();
        if rel.ends_with("tests/layering.rs") {
            // The law's own source names the spellings it bans.
            continue;
        }
        let Ok(src) = std::fs::read_to_string(&file) else {
            continue;
        };
        for (line_no, line) in src.lines().enumerate() {
            for s in spellings {
                if line.contains(s) {
                    violations.push(format!(
                        "{}:{}: the stash row `{s}` is deleted — zero spellings \
                         anywhere: {}",
                        rel,
                        line_no + 1,
                        line.trim()
                    ));
                }
            }
        }
    }
    assert!(
        violations.is_empty(),
        "the stash law: st_*/stf_* spellings reappeared —\n{}",
        violations.join("\n")
    );
}
