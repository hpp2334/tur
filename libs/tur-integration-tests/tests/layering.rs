//! The layering law — the phase-6 gate, pinned as a source-scan test.
//!
//! `core/` is MECHANISM ONLY: it must never reference `builtin_plugins`
//! (element/view types live in the plugins), and the shared builder
//! contract must never reappear (no `RutBuilder` trait, no generic
//! `el_build` / `el_child` / `el_qkey` / `el_vqkey` rows outside the
//! plugins — every family owns its spec + rows + its own `*_build`).

use std::path::{Path, PathBuf};

fn workspace_root() -> PathBuf {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    Path::new(&manifest_dir)
        .parent()
        .and_then(|p| p.parent())
        .expect("workspace root")
        .to_path_buf()
}

fn collect_rs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_rs(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}

/// Collect the rut-bearing text sources under `dir`: `.rut` packages and
/// `.rs` sources (the test corpora embed rut snippets in const strings —
/// the scans see them). Build outputs (`target/`) are skipped.
fn collect_rut_sources(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            if path.file_name().is_some_and(|n| n == "target") {
                continue;
            }
            collect_rut_sources(&path, out);
        } else if path
            .extension()
            .is_some_and(|e| e == "rs" || e == "rut")
        {
            out.push(path);
        }
    }
}

/// A line's code text: full-line comments (`// …`) are prose, not spellings
/// — the scan sees only lines that START with code.
fn code_line(line: &str) -> bool {
    !line.trim_start().starts_with("//")
}

