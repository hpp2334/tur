// Generates `cases_gen.rut` — the playground's case registry as a rut
// module fragment: `pg_case_count()`, `pg_case_name(i)`, and
// `pg_case_source(name)` over the embedded sources, plus the declared-
// tree file surface (`pg_case_file_count` / `pg_case_file_path` /
// `pg_case_file_source`) over each case's whole declared file set.
// Concatenated after `mod.rut` by the website's `playgroundSource()`
// (the two halves compile as ONE module), so the playground sidebar
// lists the curated showcase without any fetch/host I/O.
//
// The registry lists ONLY the curated showcase: the `showcase.json`
// manifest (the boa whitelist; display order = alphabetical, the same
// `.sort()` the boa reference applies). Corpus cases outside the manifest
// stay in the engine test corpus (`load_rut_bundle` covers all of them
// natively) but do not appear in the playground sidebar.
//
// Whitelist names deliberately absent from the manifest:
// - `composited-transform-anchor-playground` — removed from the corpus in
//   b3d66d1 (a JS-rail-only demo; no rut port exists or is planned).
// - `compiler-bridge-demo` — N/A by design: it demoed the JS transpile
//   bridge, which no longer exists (see the corpus README).
const fs = require("node:fs");
const path = require("node:path");

const workspaceRoot = path.resolve(__dirname, "..", "..", "..");
const engineCasesDir = path.join(workspaceRoot, "rut", "cases");
const manifestFile = path.resolve(__dirname, "..", "showcase.json");
const outFile = path.resolve(__dirname, "..", "cases_gen.rut");

const manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
if (
    !Array.isArray(manifest) ||
    manifest.some((n) => typeof n !== "string" || n === "")
) {
    console.error(
        `${path.relative(workspaceRoot, manifestFile)} must be a JSON array of case names`,
    );
    process.exit(1);
}
if (new Set(manifest).size !== manifest.length) {
    console.error(
        `${path.relative(workspaceRoot, manifestFile)} has duplicate names`,
    );
    process.exit(1);
}

// Mounting is declared, not discovered — follow `mod NAME;` /
// `pub mod NAME;` edges (the same law rut_driver::mods::mount_rows
// enforces, mirrored by the harness's `read_case_files`). Children are
// visited in sorted order, a stray undeclared directory stays invisible,
// and a declared child with no `mod.rut` on disk throws (a loud
// broken-case error, not a silent skip).
function walkModTree(caseDir) {
    const files = [];
    (function visit(dir, modPath) {
        const text = fs.readFileSync(path.join(dir, "mod.rut"), "utf8");
        files.push({ modPath, text });
        const names = [
            ...text.matchAll(
                /^[ \t]*(?:pub[ \t]+)?mod[ \t]+([A-Za-z0-9_]+)[ \t]*;/gm,
            ),
        ]
            .map((m) => m[1])
            .sort();
        for (const name of names) {
            visit(path.join(dir, name), modPath ? `${modPath}/${name}` : name);
        }
    })(caseDir, "");
    return files; // [{ modPath: "" | "explorer" | …, text }]
}

const cases = [];
for (const name of [...manifest].sort()) {
    const caseDir = path.join(engineCasesDir, name);
    const indexFile = path.join(caseDir, "mod.rut");
    if (!fs.existsSync(indexFile)) {
        console.error(
            `showcase case \`${name}\` has no ${path.relative(workspaceRoot, indexFile)}` +
                " — remove it from showcase.json or port the case",
        );
        process.exit(1);
    }
    cases.push({ name, files: walkModTree(caseDir) });
}

const esc = (s) =>
    s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

const nameArms = cases
    .map(
        (c, i) =>
            `    if (i == ${i}) {\n        return "${esc(c.name)}";\n    }`,
    )
    .join("\n");
const sourceArms = cases
    .map(
        (c) =>
            `    if (name == "${esc(c.name)}") {\n        return "${esc(c.files[0].text)}";\n    }`,
    )
    .join("\n");
const fileCountArms = cases
    .map(
        (c) =>
            `    if (name == "${esc(c.name)}") {\n        return ${c.files.length};\n    }`,
    )
    .join("\n");
const filePathArms = cases
    .map(
        (c) =>
            `    if (name == "${esc(c.name)}") {\n` +
            c.files
                .map(
                    (f, i) =>
                        `        if (i == ${i}) {\n            return "${esc(f.modPath)}";\n        }`,
                )
                .join("\n") +
            `\n    }`,
    )
    .join("\n");
const fileSourceArms = cases
    .flatMap((c) =>
        c.files.map(
            (f) =>
                `    if (name == "${esc(c.name)}" && path == "${esc(f.modPath)}") {\n        return "${esc(f.text)}";\n    }`,
        ),
    )
    .join("\n");

const code = `// AUTO-GENERATED by scripts/gen-cases.cjs — do not edit.
// The playground's case registry: one entry per showcase.json manifest
// name (rut/cases/<name>/), alphabetical. The file fns expose each
// case's DECLARED module tree: "" = the root mod.rut (always index 0),
// declared children slash-joined ("landing") in sorted mod-path order.
// pg_case_source is the legacy whole-case embedding — kept until the
// playground-UI phase retires it (its call sites live in mod.rut).

fn pg_case_count() -> u64 {
    return ${cases.length};
}

fn pg_case_name(i: u64) -> str {
${nameArms}
    return "";
}

// Legacy whole-case embedding — removed in the playground-UI phase
// (pg_case_file_source below is its multi-file replacement).
fn pg_case_source(name: str) -> str {
${sourceArms}
    return "";
}

fn pg_case_file_count(name: str) -> u64 {
${fileCountArms}
    return 0;
}

fn pg_case_file_path(name: str, i: u64) -> str {
${filePathArms}
    return "";
}

fn pg_case_file_source(name: str, path: str) -> str {
${fileSourceArms}
    return "";
}
`;

fs.writeFileSync(outFile, code);
console.log(
    `generated cases_gen.rut with ${cases.length} cases (${cases.reduce((n, c) => n + c.files.length, 0)} files)`,
);
